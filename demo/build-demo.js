#!/usr/bin/env node
/*
 * Builds the offline demo of the AgriLab website and staff system.
 *
 *   node demo/build-demo.js [output-folder]
 *
 * The output folder opens straight from disk (double-click), with no internet and no Google Sheet:
 * the demo's ops/config.js carries the real Apps Script code (apps-script/Code.gs) plus a stand-in for
 * Google Sheets that keeps records in the browser. Links are rewritten to point at index.html files,
 * because pages opened from disk don't resolve folder links.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, '..', 'agrilab-demo'));
const SKIP = new Set(['.git', 'demo', 'CNAME', '.nojekyll', 'robots.txt', '404.html']);

fs.rmSync(OUT, { recursive: true, force: true });
(function copy(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (from === ROOT && SKIP.has(e.name)) continue;
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copy(a, b); else fs.copyFileSync(a, b);
  }
})(ROOT, OUT);

function edit(rel, pairs) {
  const f = path.join(OUT, rel); let s = fs.readFileSync(f, 'utf8');
  for (const [a, b] of pairs) {
    if (!s.includes(a)) throw new Error(`${rel}: expected to find ${a}`);
    s = s.split(a).join(b);
  }
  fs.writeFileSync(f, s);
}
edit('index.html', [['href="ops/"', 'href="ops/index.html"'], ['href="visit/"', 'href="visit/index.html"'], ['href="portal/"', 'href="portal/index.html"']]);
edit('portal/index.html', [['href="../"', 'href="../index.html"']]);
edit('visit/index.html', [['href="../"', 'href="../index.html"']]);
edit('ops/index.html', [["new URL('../visit/', location.href)", "new URL('../visit/index.html', location.href)"], ["new URL('../portal/', location.href)", "new URL('../portal/index.html', location.href)"]]);

const backend = fs.readFileSync(path.join(__dirname, 'local-backend.js'), 'utf8');
const code = fs.readFileSync(path.join(ROOT, 'apps-script', 'Code.gs'), 'utf8');
// Code.gs is loaded first so its functions exist; the backend then defines the Google stand-ins it calls at run time.
fs.writeFileSync(path.join(OUT, 'ops', 'config.js'),
  `// Offline demo build: generated by demo/build-demo.js. Do not deploy this file.\n${code}\n\n${backend}`);
fs.rmSync(path.join(OUT, 'apps-script'), { recursive: true, force: true });

const cmd = (target) => `@echo off\r\nstart "" "%~dp0${target}"\r\n`;
fs.writeFileSync(path.join(OUT, 'Open staff system.cmd'), cmd('ops\\index.html'));
fs.writeFileSync(path.join(OUT, 'Open website.cmd'), cmd('index.html'));
fs.writeFileSync(path.join(OUT, 'Open visitors book.cmd'), cmd('visit\\index.html'));
fs.writeFileSync(path.join(OUT, 'Open client portal.cmd'), cmd('portal\\index.html'));
